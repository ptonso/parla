"""Canonical grid -> booktabs LaTeX.

The only place table LaTeX is written, so every table in the document is aligned and escaped
the same way. The `\\providecommand` preamble makes the artifact self-contained: no-ops when
the project loads `booktabs`, `\\hline` fallbacks when it does not (the paper
starter does not, and is hand-authored, so parla cannot retrofit it).
"""

from __future__ import annotations

import re

from ..names import NAME
from .table_fit import FitPlan
from .table_parse import TableGrid, grid_citekeys

# Beyond this width a column reads as prose and gets a wrapped `p{}`. Kept generous: a
# metric string like "Acc. 0.872 / F1_macro 0.844" must not be broken across lines.
LONG_TEXT_THRESHOLD = 40
_MIN_P_FRACTION = 0.10
_MAX_P_FRACTION = 0.60
_P_WIDTH_BUDGET = 0.90

_BOOKTABS_SHIM = (
    r"\providecommand{\toprule}{\hline}",
    r"\providecommand{\midrule}{\hline}",
    r"\providecommand{\bottomrule}{\hline}",
)

_LATEX_ESCAPES = (
    ("\\", r"\textbackslash{}"),
    ("{", r"\{"),
    ("}", r"\}"),
    ("&", r"\&"),
    ("%", r"\%"),
    ("$", r"\$"),
    ("#", r"\#"),
    ("_", r"\_"),
    ("^", r"\textasciicircum{}"),
    ("~", r"\textasciitilde{}"),
)

_PASSTHROUGH_RE = re.compile(
    r"(?P<math>\$[^$]*\$)"
    r"|[~ ]*<\s*(?:full-bib|bib):(?P<citekeys>[^<>]+?)\s*>"
    # A condensed cell may echo a citation as a markdown link into `../bib/<key>.md` instead of
    # the `<bib:key>` marker; treated the same as citekeys above rather than passed through as
    # literal, unescaped markdown.
    r"|[~ ]*\[[^\]]*\]\(\s*(?:\.\./)*bib/(?P<md_citekey>[^)/]+?)(?:\.md)?\s*\)"
    r"|(?P<marker>\*\*|\*|`)(?P<body>.+?)(?P=marker)"
)
# Split on separators first, so "0.93 ± 0.02" is two numbers rather than one bad one.
_NUMERIC_SPLIT_RE = re.compile(r"±|\+/-|\\pm|--|–|—|/")
_NUMERIC_STRIP_RE = re.compile(r"[%,()\s]")


def render_table_artifact(grid: TableGrid, plan: FitPlan, *, source: str) -> str:
    lines = [
        f"% Generated by {NAME} from {source} - do not edit; edit the source and re-run",
        f"% `{NAME} tool table`.",
        *_BOOKTABS_SHIM,
        "",
    ]

    legend = grid_citekeys(grid) if plan.hoist_citations else []
    tabular = _render_tabular(grid, plan, legend=legend)
    if plan.resize:
        lines.append(r"\resizebox{\linewidth}{!}{%")
        lines.append(tabular)
        lines.append("}")
    else:
        lines.append(tabular)

    if legend:
        lines.append(_render_legend(legend))

    body = "\n".join(lines)
    return body if body.endswith("\n") else body + "\n"


def _render_legend(citekeys: list[str]) -> str:
    """Numbered citation key printed under the tabular, inside the float.

    Kept out of `\\resizebox` so it stays at a readable size, and left-aligned in a minipage
    because the enclosing float centres its contents.
    """
    entries = "\\quad\n".join(
        rf"[{index}]~\cite{{{key}}}" for index, key in enumerate(citekeys, start=1)
    )
    return "\n".join(
        [
            r"\par\vspace{2pt}",
            r"\begin{minipage}{\linewidth}\footnotesize\raggedright",
            entries,
            r"\end{minipage}",
        ]
    )


def _render_tabular(grid: TableGrid, plan: FitPlan, *, legend: list[str] | None = None) -> str:
    column_spec = build_column_spec(grid, plan)
    rows = [
        r"\toprule",
        _render_row(grid.header, legend=legend),
        r"\midrule",
        *(_render_row(row, legend=legend) for row in grid.rows),
        r"\bottomrule",
    ]
    inner = "\n".join(f"    {line}" for line in rows)
    tabular = f"\\begin{{tabular}}{{{column_spec}}}\n{inner}\n\\end{{tabular}}"

    if plan.font_step == "normalsize":
        return tabular
    # Grouped so the size change cannot leak into the caption.
    return f"{{\\{plan.font_step}\n{tabular}\n}}"


def build_column_spec(grid: TableGrid, plan: FitPlan) -> str:
    widths = plan.measure.col_widths
    total = sum(widths) or 1
    spec: list[str] = []
    for index in range(grid.n_cols):
        cells = [cell for cell in grid.column(index)[1:] if cell]
        if cells and all(_is_numeric_cell(cell) for cell in cells):
            spec.append("r")
        elif widths[index] > LONG_TEXT_THRESHOLD:
            fraction = min(_MAX_P_FRACTION, max(_MIN_P_FRACTION, widths[index] / total * _P_WIDTH_BUDGET))
            spec.append(f"p{{{fraction:.2f}\\linewidth}}")
        else:
            spec.append("l")
    return "".join(spec)


def _render_row(cells: list[str], *, legend: list[str] | None = None) -> str:
    return " & ".join(escape_cell(cell, legend=legend) for cell in cells) + r" \\"


def escape_cell(cell: str, *, legend: list[str] | None = None) -> str:
    """Escape LaTeX specials, but honour the markup a table source is allowed to carry.

    Inline `$...$` math passes through untouched and Markdown emphasis becomes its LaTeX
    equivalent. A `<bib:key>` marker, or a markdown `[label](../bib/key.md)` citation link,
    becomes a real `\\cite` normally, or a short `[n]` pointing at the table's legend when one is
    being emitted. Everything else is escaped literally.
    """
    parts: list[str] = []
    cursor = 0
    for match in _PASSTHROUGH_RE.finditer(cell):
        parts.append(_escape_plain(cell[cursor : match.start()]))
        parts.append(_render_markup(match, legend=legend))
        cursor = match.end()
    parts.append(_escape_plain(cell[cursor:]))
    return "".join(parts)


def _render_markup(match: re.Match[str], *, legend: list[str] | None = None) -> str:
    if match.group("math") is not None:
        return match.group("math")
    citekeys_raw = match.group("citekeys")
    if citekeys_raw is None:
        citekeys_raw = match.group("md_citekey")
    if citekeys_raw is not None:
        keys = [key.strip() for key in citekeys_raw.split(",") if key.strip()]
        if legend:
            numbers = ", ".join(str(legend.index(key) + 1) for key in keys if key in legend)
            return f"~[{numbers}]" if numbers else ""
        return f"~\\cite{{{', '.join(keys)}}}"
    marker, body = match.group("marker"), match.group("body")
    command = {"**": "textbf", "*": "emph", "`": "texttt"}[marker]
    return f"\\{command}{{{_escape_plain(body)}}}"


def _escape_plain(text: str) -> str:
    for literal, replacement in _LATEX_ESCAPES:
        text = text.replace(literal, replacement)
    return text


def _is_numeric_cell(cell: str) -> bool:
    tokens = [token for token in _NUMERIC_SPLIT_RE.split(cell) if token.strip()]
    if not tokens:
        return False
    for token in tokens:
        candidate = _NUMERIC_STRIP_RE.sub("", token)
        if not candidate:
            return False
        try:
            float(candidate)
        except ValueError:
            return False
    return True
