# --- measure ---------------------------------------------------------------------------


def test_count_words_drops_markup_and_keeps_link_labels():
    text = "\\section{Intro} We % a comment\nuse $x_i$ and [AcmeTrees](bib/acme.md) \\cite{a}.\n"
    assert measure.count_words(text) == 8  # Intro We use x i and AcmeTrees a


def test_words_per_file_follow_the_input_tree_inside_the_artifact(project):
    make_artifact(project, "p", {
        "main.tex": "one two\n\\input{artifacts/p/section/a}\n\\input{sources/ext}\n",
        "section/a.tex": "three four five\n",
    })
    (project / "parla/sources").mkdir(exist_ok=True)
    (project / "parla/sources/ext.tex").write_text("outside the artifact words\n")
    counted = measure.words(project, "p")
    assert [f for f, _ in counted] == ["artifacts/p/main.tex", "artifacts/p/section/a.tex"]
    assert counted[1][1] == 3


def test_body_pages_read_the_anchor_from_the_aux(tmp_path, monkeypatch):
    pdf, aux = tmp_path / "p.pdf", tmp_path / "main.aux"
    pdf.write_bytes(b"%PDF")
    monkeypatch.setattr(measure, "pdf_page_count", lambda p: 9)
    aux.write_text("\\newlabel{parla:body-end}{{}{8}{x}{section.4}{}}\n")
    assert measure.body_pages(pdf, aux) == measure.Pages(total=9, body=8)
    aux.write_text("\\newlabel{parla:body-end}{{1}{7}}\n")
    assert measure.body_pages(pdf, aux).body == 7
    aux.write_text("nothing\n")
    with pytest.raises(EngineError, match="parla:body-end"):
        measure.body_pages(pdf, aux)
    with pytest.raises(EngineError, match="run `build` first"):
        measure.body_pages(tmp_path / "missing.pdf", aux)


def test_pdf_page_count_parses_pdfinfo(tmp_path, monkeypatch):
    class R:
        returncode, stdout, stderr = 0, "Title: x\nPages:          12\n", ""

    monkeypatch.setattr(measure.subprocess, "run", lambda *a, **k: R())
    assert measure.pdf_page_count(tmp_path / "a.pdf") == 12


def test_measure_command_words_and_the_engine_without_pages(project, capsys):
    router.init_artifact(project, "post", "social-post", "linkedin")
