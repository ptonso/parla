SECTIONS = [
    Section("introduction", 1, 2, "We study trees."),
    Section("method", 3, 4, "Method text."),
    Section("results", 5, 6, "Results text."),
]


def test_render_filters_by_section_and_pages():
    assert source.render(SECTIONS).count("## ") == 3
    assert source.render(SECTIONS, label="method") == "## method (pp. 3-4)\nMethod text."
    assert source.render(SECTIONS, pages=(4, 5)).splitlines()[0] == "## method (pp. 3-4)"
    with pytest.raises(SourceError, match="have: introduction, method, results"):
        source.render(SECTIONS, label="ghost")


def test_find_pdf_uses_the_file_field_then_attachments(tmp_path, monkeypatch):
    lib = tmp_path / "lib" / "library.bib"
    lib.parent.mkdir()
    lib.write_text("@article{a2020, title={A}, file={papers/a.pdf}}\n@article{b2020, title={B}}\n@article{c2020, title={C}}\n")
    meta = tmp_path / "library.json"
    pdf = tmp_path / "att.pdf"
    pdf.write_bytes(b"%PDF")
    meta.write_text(json.dumps({"items": [{"citationKey": "b2020", "attachments": [{"path": str(pdf)}]}]}))
    (lib.parent / "papers").mkdir()
    (lib.parent / "papers/a.pdf").write_bytes(b"%PDF")
    monkeypatch.setattr(config, "library_bib", lambda: lib)
    monkeypatch.setattr(config, "library_json", lambda: meta)
    assert source.find_pdf("a2020") == (lib.parent / "papers/a.pdf").resolve()
    assert source.find_pdf("b2020") == pdf.resolve()
    with pytest.raises(SourceError, match="no readable PDF"):
        source.find_pdf("c2020")
    with pytest.raises(SourceError, match="no entry in the library"):
        source.find_pdf("ghost")


def test_sections_are_cached_until_the_pdf_changes(tmp_path, monkeypatch):
    pdf = tmp_path / "a.pdf"
    pdf.write_bytes(b"one")
    monkeypatch.setenv("XDG_CACHE_HOME", str(tmp_path / "cache"))
    monkeypatch.setattr(source, "find_pdf", lambda key: pdf)
    runs = []

    class Extractor:
        def ensure_available(self):
            pass

        def extract_pages(self, path, config):
            runs.append(path.read_bytes())
            return ["page"]

    monkeypatch.setattr(source, "get_pdf_extractor", lambda name: Extractor())
    monkeypatch.setattr(source, "_cleanup_canonical_pages", lambda raw, cfg: raw)
    monkeypatch.setattr(source, "_segment_sections", lambda pages: [{"label": "body", "page_start": 1, "page_end": 1, "text": f"text {len(runs)}"}])
    monkeypatch.setattr(source, "_filter_sections", lambda secs, settings: secs)

    first = source.load_sections("a2020")
    assert first == [Section("body", 1, 1, "text 1")] and (tmp_path / "cache/parla/source/a2020.json").is_file()
    assert source.load_sections("a2020") == first and len(runs) == 1
    pdf.write_bytes(b"two")
    assert source.load_sections("a2020") == [Section("body", 1, 1, "text 2")] and len(runs) == 2


def test_source_without_the_pdf_extra_names_it(tmp_path, monkeypatch):
    pdf = tmp_path / "a.pdf"
    pdf.write_bytes(b"x")
    monkeypatch.setenv("XDG_CACHE_HOME", str(tmp_path / "cache"))
    monkeypatch.setattr(source, "find_pdf", lambda key: pdf)
    import builtins

    real = builtins.__import__

    def deny(name, *a, **k):
        if name == "pymupdf4llm":
            raise ModuleNotFoundError(name)
        return real(name, *a, **k)

    monkeypatch.setattr(builtins, "__import__", deny)
    with pytest.raises(RuntimeError, match="pdf. extra"):
        source.load_sections("a2020")
